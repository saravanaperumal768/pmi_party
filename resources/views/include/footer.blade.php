            }


            // Image Preview
            else {

                const imageUrl =
                    URL.createObjectURL(file);

                preview.innerHTML = `
                <img
                    src="${imageUrl}"
                    alt="Voter ID Preview"
                    style="
                        width:300px;
                        max-height:300px;
                        object-fit:contain;
                        border:1px solid #ddd;
                        border-radius:5px;
                    ">
            `;
            }

        };


        // =========================================================
        // FORM SUBMIT - FINAL JS VALIDATION + AJAX
        // =========================================================
        form.addEventListener('submit', function(e) {

            e.preventDefault();


            // -----------------------------------------------------
            // Validate Step 4 first
            // -----------------------------------------------------
            if (!validateStep(currentStep)) {

                Swal.fire({
                    icon: 'warning',
                    title: 'Validation Error',
                    text: 'Please correct the highlighted fields.'
                });

                return;
            }


            // -----------------------------------------------------
            // Validate ALL STEPS before AJAX
            // -----------------------------------------------------
            let firstInvalidStep = -1;

            for (let i = 0; i < steps.length; i++) {

                if (!validateStep(i)) {

                    firstInvalidStep = i;

                    break;
                }
            }


            // If any previous step has an error
            if (firstInvalidStep !== -1) {

                currentStep = firstInvalidStep;

                showStep(currentStep);

                Swal.fire({
                    icon: 'warning',
                    title: 'Validation Error',
                    text: 'Please correct the highlighted fields.'
                });

                return;
            }


            // -----------------------------------------------------
            // Create FormData
            // -----------------------------------------------------
            const formData =
                new FormData(form);


            // -----------------------------------------------------
            // CSRF
            // -----------------------------------------------------
            const csrfToken =
                document.querySelector(
                    'input[name="_token"]'
                ).value;


            // -----------------------------------------------------
            // Submit button
            // -----------------------------------------------------
            const submitButton =
                form.querySelector('.submit');

            submitButton.disabled = true;

            submitButton.innerText =
                'Submitting...';


            // -----------------------------------------------------
            // Clear old errors
            // -----------------------------------------------------
            document.querySelectorAll(
                '.error-message'
            ).forEach(function(element) {

                element.innerText = '';
            });

            document.querySelectorAll(
                '.error-border'
            ).forEach(function(element) {

                element.classList.remove(
                    'error-border'
                );
            });


            // -----------------------------------------------------
            // AJAX
            // -----------------------------------------------------
            fetch(form.action, {

                    method: 'POST',

                    body: formData,

                    headers: {

                        'X-CSRF-TOKEN': csrfToken,

                        'Accept': 'application/json'
                    }

                })


                // -----------------------------------------------------
                // RESPONSE
                // -----------------------------------------------------
                .then(async function(response) {

                    const data =
                        await response.json();


                    // Laravel validation error
                    if (response.status === 422) {

                        handleBackendErrors(
                            data.errors
                        );

                        throw new Error(
                            'VALIDATION_ERROR'
                        );
                    }


                    // Server error
                    if (!response.ok) {

                        throw new Error(
                            data.message ||
                            'Something went wrong'
                        );
                    }


                    return data;

                })


                // -----------------------------------------------------
                // SUCCESS
                // -----------------------------------------------------
                .then(function(data) {

                    if (data.status === true) {

                        Swal.fire({

                            icon: 'success',

                            title: 'Registration Successful',

                            text: data.message,

                            confirmButtonText: 'OK'

                        }).then(function() {

                            // Reset form
                            form.reset();


                            // Reset photo preview
                            const uploadedImage =
                                document.getElementById(
                                    'uploadedImage'
                                );

                            if (uploadedImage) {

                                uploadedImage.src = '';

                                uploadedImage.style.display =
                                    'none';
                            }


                            // Reset ID proof preview
                            const filePreview =
                                document.getElementById(
                                    'filePreview'
                                );

                            if (filePreview) {
                                filePreview.innerHTML = '';
                            }


                            // Remove errors
                            document.querySelectorAll(
                                '.error-border'
                            ).forEach(function(element) {

                                element.classList.remove(
                                    'error-border'
                                );
                            });


                            document.querySelectorAll(
                                '.error-message'
                            ).forEach(function(element) {

                                element.innerText = '';
                            });


                            // First step
                            currentStep = 0;

                            showStep(currentStep);

                        });

                    }

                })


                // -----------------------------------------------------
                // ERROR
                // -----------------------------------------------------
                .catch(function(error) {

                    console.error(error);


                    // Don't show second Swal for validation errors
                    if (
                        error.message ===
                        'VALIDATION_ERROR'
                    ) {
                        return;
                    }


                    Swal.fire({

                        icon: 'error',

                        title: 'Registration Failed',

                        text: error.message ||
                            'Unable to complete registration.'

                    });

                })


                // -----------------------------------------------------
                // FINALLY
                // -----------------------------------------------------
                .finally(function() {

                    submitButton.disabled = false;

                    submitButton.innerText =
                        'Complete Registration';

                });

        });


        // =========================================================
        // HANDLE LARAVEL BACKEND ERRORS
        // =========================================================
        function handleBackendErrors(errors) {

            let firstErrorField = null;

            let errorMessages = [];


            // Clear old errors
            document.querySelectorAll(
                '.error-message'
            ).forEach(function(element) {

                element.innerText = '';
            });

            document.querySelectorAll(
                '.error-border'
            ).forEach(function(element) {

                element.classList.remove(
                    'error-border'
                );
            });


            // Process errors
            Object.keys(errors).forEach(function(key) {

                const message =
                    errors[key][0];

                errorMessages.push(message);


                // Radio buttons need special handling
                const input =
                    document.querySelector(
                        `[name="${key}"]`
                    );


                if (input) {

                    input.classList.add(
                        'error-border'
                    );


                    const formGroup =
                        input.closest('.form-group');


                    const errorBox =
                        formGroup?.querySelector(
                            '.error-message'
                        );


                    if (errorBox) {

                        errorBox.innerText =
                            message;
                    }


                    if (!firstErrorField) {

                        firstErrorField =
                            input;
                    }
                }

            });


            // Move to first error step
            if (firstErrorField) {

                const stepElement =
                    firstErrorField.closest(
                        '.form-step'
                    );


                const stepIndex =
                    steps.indexOf(stepElement);


                if (stepIndex !== -1) {

                    currentStep =
                        stepIndex;

                    showStep(
                        currentStep
                    );
                }


                setTimeout(function() {

                    firstErrorField.scrollIntoView({

                        behavior: 'smooth',

                        block: 'center'

                    });

                }, 300);
            }


            // Backend error popup
            Swal.fire({

                icon: 'error',

                title: 'Validation Error',

                html: errorMessages.join('<br>')

            });
        }


        // =========================================================
        // INITIAL STEP
        // =========================================================
        showStep(currentStep);

    });
</script>

