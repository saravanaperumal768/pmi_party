<script>
    document.addEventListener('DOMContentLoaded', function() {

        const form = document.getElementById('registrationForm');
        const steps = Array.from(document.querySelectorAll('.form-step'));
        const stepItems = Array.from(document.querySelectorAll('.step-item'));

        let currentStep = 0;

        // =========================================================
        // SHOW STEP
        // =========================================================
        function showStep(stepIndex) {

            steps.forEach((step, index) => {
                step.classList.toggle('active', index === stepIndex);
            });

            updateStepIndicators();
        }


        // =========================================================
        // STEP INDICATORS
        // =========================================================
        function updateStepIndicators() {

            stepItems.forEach((item, index) => {

                item.classList.toggle(
                    'active',
                    index === currentStep
                );

                item.classList.toggle(
                    'completed',
                    index < currentStep
                );
            });
        }


        // =========================================================
        // CLEAR FIELD ERROR
        // =========================================================
        function clearFieldError(input) {

            input.classList.remove('error-border');

            const formGroup = input.closest('.form-group');

            if (!formGroup) {
                return;
            }

            const errorBox =
                formGroup.querySelector('.error-message');

            if (errorBox) {
                errorBox.innerText = '';
            }
        }


        // =========================================================
        // SHOW FIELD ERROR
        // =========================================================
        function showFieldError(input, message) {

            input.classList.add('error-border');

            const formGroup = input.closest('.form-group');

            if (!formGroup) {
                return;
            }

            const errorBox =
                formGroup.querySelector('.error-message');

            if (errorBox) {
                errorBox.innerText = message;
            }
        }


        // =========================================================
        // VALIDATE TEXT / SELECT / TEXTAREA
        // =========================================================
        function validateRequiredField(input) {
            if (!input) {
                return false;
            }

            const value = String(input.value || '').trim();

            if (value === '') {
                if (input.tagName === 'SELECT') {
                    showFieldError(input, 'Please select an option');
                } else {
                    showFieldError(input, 'This field is required');
                }

                return false;
            }

            clearFieldError(input);
            return true;
        }


        // =========================================================
        // VALIDATE MOBILE
        // =========================================================
        function validateMobile() {

            const input =
                document.getElementById('mobile_number');

            if (!input) return true;

            const value = input.value.trim();

            if (!value) {
                showFieldError(
                    input,
                    'Mobile number is required'
                );
                return false;
            }

            if (!/^[6-9][0-9]{9}$/.test(value)) {

                showFieldError(
                    input,
                    'Enter valid 10 digit mobile number'
                );

                return false;
            }

            clearFieldError(input);

            return true;
        }


        // =========================================================
        // VALIDATE EMAIL
        // =========================================================
        function validateEmail() {

            const input =
                document.getElementById('email');

            if (!input) return true;

            const value = input.value.trim();

            if (!value) {

                showFieldError(
                    input,
                    'Email is required'
                );

                return false;
            }

            const emailRegex =
                /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

            if (!emailRegex.test(value)) {

                showFieldError(
                    input,
                    'Enter a valid email address'
                );

                return false;
            }

            clearFieldError(input);

            return true;
        }


        // =========================================================
        // VALIDATE DOB
        // =========================================================
        function validateDOB() {

            const input = document.getElementById('dob');

            if (!input) {
                return true;
            }

            const value = String(input.value || '').trim();

            // Empty DOB
            if (value === '') {

                showFieldError(
                    input,
                    'Date of birth is required'
                );

                return false;
            }

            const dobDate = new Date(value + 'T00:00:00');

            if (isNaN(dobDate.getTime())) {

                showFieldError(
                    input,
                    'Please enter a valid date of birth'
                );

                return false;
            }

            // Today
            const today = new Date();
            today.setHours(0, 0, 0, 0);

            // Future / today
            if (dobDate >= today) {

                showFieldError(
                    input,
                    'Date of birth must be before today'
                );

                return false;
            }

            // Calculate age
            let age =
                today.getFullYear() -
                dobDate.getFullYear();

            const monthDifference =
                today.getMonth() -
                dobDate.getMonth();

            if (
                monthDifference < 0 ||
                (
                    monthDifference === 0 &&
                    today.getDate() < dobDate.getDate()
                )
            ) {
                age--;
            }

            // Below 18
            if (age < 18) {

                showFieldError(
                    input,
                    'You must be 18 years or older to apply'
                );

                return false;
            }

            clearFieldError(input);

            // Store calculated age in hidden field
            const ageInput =
                document.getElementById('age');

            if (ageInput) {
                ageInput.value = age;
            }

            return true;
        }


        // =========================================================
        // VALIDATE RADIO GROUP
        // =========================================================
        function validateRadioGroup(stepElement, name) {

            const radios =
                stepElement.querySelectorAll(
                    `input[name="${name}"]`
                );

            if (!radios.length) {
                return true;
            }

            const checked =
                stepElement.querySelector(
                    `input[name="${name}"]:checked`
                );

            const formGroup =
                radios[0].closest('.form-group');

            const errorBox =
                formGroup?.querySelector('.error-message');

            if (!checked) {

                if (errorBox) {
                    errorBox.innerText =
                        'Please select an option';
                }

                return false;
            }

            if (errorBox) {
                errorBox.innerText = '';
            }

            return true;
        }


        // =========================================================
        // FILE VALIDATION
        // =========================================================
        function validateFile(input, allowedTypes, maxSize, message) {

            if (!input) {
                return false;
            }

            // No file selected
            if (!input.files || input.files.length === 0) {

                showFieldError(
                    input,
                    'This file is required'
                );

                return false;
            }

            const file = input.files[0];

            // File type
            if (!allowedTypes.includes(file.type)) {

                showFieldError(
                    input,
                    message
                );

                return false;
            }

            // File size
            if (file.size > maxSize) {

                showFieldError(
                    input,
                    'File size must not exceed 1 MB'
                );

                return false;
            }

            // Valid
            clearFieldError(input);

            return true;
        }


        // =========================================================
        // VALIDATE CURRENT STEP
        // =========================================================
        function validateStep(stepIndex) {

            const currentStepElement =
                steps[stepIndex];

            let isValid = true;


            // =====================================================
            // STEP 1
            // =====================================================
            if (stepIndex === 0) {

                const requiredFields = [
                    'name',
                    'father_name',
                    'community',
                ];

                requiredFields.forEach(function(name) {

                    const input =
                        currentStepElement.querySelector(
                            `[name="${name}"]`
                        );

                    if (input) {

                        if (!validateRequiredField(input)) {
                            isValid = false;
                        }
                    }
                });


                // IMPORTANT: DOB validation
                if (!validateDOB()) {
                    isValid = false;
                }


                // Gender
                if (!validateRadioGroup(
                        currentStepElement,
                        'gender'
                    )) {
                    isValid = false;
                }


                // Marital status
                if (!validateRadioGroup(
                        currentStepElement,
                        'martialstatus'
                    )) {
                    isValid = false;
                }
            }


            // =====================================================
            // STEP 2
            // =====================================================
            if (stepIndex === 1) {

                const requiredFields = [
                    'blood_group',
                    'qualification',
                    'occupation',
                    'social_media'
                ];

                requiredFields.forEach(function(name) {

                    const input =
                        currentStepElement.querySelector(
                            `[name="${name}"]`
                        );

                    if (input) {

                        if (!validateRequiredField(input)) {
                            isValid = false;
                        }
                    }
                });


                // Mobile
                if (!validateMobile()) {
                    isValid = false;
                }


                // Email
                if (!validateEmail()) {
                    isValid = false;
                }
            }


            // =====================================================
            // STEP 3
            // =====================================================
            if (stepIndex === 2) {

                const requiredFields = [
                    'state',
                    'constitution',
                    'district',
                    'taluk',
                    'block',
                    'part',
                    'address'
                ];

                requiredFields.forEach(function(name) {

                    const input =
                        currentStepElement.querySelector(
                            `[name="${name}"]`
                        );

                    if (input) {

                        if (!validateRequiredField(input)) {
                            isValid = false;
                        }
                    }
                });


                // Other details is optional
                const otherDetails =
                    currentStepElement.querySelector(
                        '[name="other_details"]'
                    );

                if (otherDetails) {
                    clearFieldError(otherDetails);
                }
            }


            // =====================================================
            // STEP 4
            // =====================================================
            // =====================================================
            // STEP 4 - ID PROOF
            // =====================================================
            if (stepIndex === 3) {

                // PHOTO
                const photo = document.getElementById('photo');

                if (photo) {

                    if (!validateFile(
                            photo,
                            ['image/png', 'image/jpeg'],
                            1024 * 1024,
                            'Only PNG, JPG and JPEG images are allowed'
                        )) {
                        isValid = false;
                    }
                }


                // VOTER ID
                const voterId =
                    document.getElementById('voter_id');

                if (voterId) {

                    if (!validateRequiredField(voterId)) {
                        isValid = false;
                    }
                }


                // VOTER ID PROOF
                const idProof =
                    document.getElementById('id_proof');

                if (idProof) {

                    if (!validateFile(
                            idProof,
                            [
                                'application/pdf',
                                'image/png',
                                'image/jpeg'
                            ],
                            1024 * 1024,
                            'Only PDF, PNG, JPG and JPEG files are allowed'
                        )) {
                        isValid = false;
                    }
                }
            }


            return isValid;
        }


        // =========================================================
        // NEXT BUTTON
        // =========================================================
        document.querySelectorAll('.next').forEach(function(button) {

            button.addEventListener('click', function() {

                // Validate current step FIRST
                const valid =
                    validateStep(currentStep);

                if (!valid) {

                    Swal.fire({
                        icon: 'warning',
                        title: 'Validation Error',
                        text: 'Please correct the highlighted fields.'
                    });

                    return;
                }


                // Move to next step
                if (currentStep < steps.length - 1) {

                    currentStep++;

                    showStep(currentStep);

                    window.scrollTo({
                        top: 0,
                        behavior: 'smooth'
                    });
                }

            });

        });


        // =========================================================
        // PREVIOUS BUTTON
        // =========================================================
        document.querySelectorAll('.prev').forEach(function(button) {

            button.addEventListener('click', function() {

                if (currentStep > 0) {

                    currentStep--;

                    showStep(currentStep);

                    window.scrollTo({
                        top: 0,
                        behavior: 'smooth'
                    });
                }

            });

        });


        // =========================================================
        // MOBILE INPUT
        // =========================================================
        const mobile =
            document.getElementById('mobile_number');

        if (mobile) {

            mobile.addEventListener('input', function() {

                this.value =
                    this.value.replace(/\D/g, '')
                    .substring(0, 10);

                if (this.value.length === 10) {
                    validateMobile();
                } else {
                    clearFieldError(this);
                }

            });
        }


        // =========================================================
        // EMAIL INPUT
        // =========================================================
        const email =
            document.getElementById('email');

        if (email) {

            email.addEventListener('blur', function() {

                if (this.value.trim()) {
                    validateEmail();
                }

            });
        }


        // =========================================================
        // DOB - SET MAX DATE
        // =========================================================
        const dob =
            document.getElementById('dob');

        if (dob) {

            const today =
                new Date().toISOString().split('T')[0];

            dob.setAttribute('max', today);
        }


        // =========================================================
        // PHOTO PREVIEW
        // =========================================================
        window.previewImage = function(input) {

            const image =
                document.getElementById('uploadedImage');

            const formGroup =
                input.closest('.form-group');

            const errorBox =
